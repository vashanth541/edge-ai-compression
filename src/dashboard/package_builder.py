"""Deployment package builder for the Compression Framework.

Assembles a downloadable ZIP archive containing:
  - The .tflite model
  - Generated C/C++ model-data header (model_data.h)
  - Class labels header (model_labels.h)
  - JSON machine-readable report
  - Human-readable Markdown compatibility report
  - Integration scaffold (example main.cpp for ESP32-S3 / TFLM)
  - Manifest with artifact names, sizes, and SHA-256 hashes

All status labels reflect what was actually achieved, not aspirational states.
"""

from __future__ import annotations

import datetime
import hashlib
import io
import json
import zipfile
from pathlib import Path
from typing import Any, Dict, List, Optional, Union

import numpy as np


class _NumpyEncoder(json.JSONEncoder):
    """JSON encoder that handles numpy scalars and arrays from TFLite interpreter."""
    def default(self, obj: Any) -> Any:
        if isinstance(obj, np.ndarray):
            return obj.tolist()
        if isinstance(obj, (np.integer,)):
            return int(obj)
        if isinstance(obj, (np.floating,)):
            return float(obj)
        if isinstance(obj, (np.bool_,)):
            return bool(obj)
        return super().default(obj)


