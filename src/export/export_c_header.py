"""C header export utility for embedded microcontroller deployment.

Converts a validated TensorFlow Lite model FlatBuffer into a byte-for-byte identical
C byte array header with 8-byte alignment, and generates corresponding class label definitions.
"""

from __future__ import annotations

import datetime
import hashlib
import json
from pathlib import Path
import re
from typing import Any, Dict, List, Optional, Tuple, Union

from src.audio.config import DatasetConfig, load_config


def export_tflite_to_c_header(
    tflite_path: Union[str, Path],
    output_header_path: Union[str, Path],
    labels_header_path: Optional[Union[str, Path]] = None,
    manifest_path: Optional[Union[str, Path]] = None,
    array_name: str = "g_model_data",
    len_name: str = "g_model_data_len",
) -> Dict[str, Any]:
    """Export a TFLite model file to a C/C++ header containing a byte array.

    Args:
        tflite_path: Path to the validated .tflite model.
        output_header_path: Path to write the C header (e.g., model_data.h).
        labels_header_path: Optional path to write class labels header (e.g., model_labels.h).
        manifest_path: Optional path to write export verification manifest (JSON).
        array_name: C array variable name.
        len_name: C length variable name.

    Returns:
        Dict containing export metadata: byte_length, sha256, paths.
    """
    tflite_p = Path(tflite_path).resolve()
    if not tflite_p.is_file():
        raise FileNotFoundError(f"Source model file not found: {tflite_p}")

    with open(tflite_p, "rb") as f:
        model_bytes = f.read()

    byte_len = len(model_bytes)
    if byte_len == 0:
        raise ValueError(f"Source model file is empty: {tflite_p}")

    sha256_hash = hashlib.sha256(model_bytes).hexdigest()
    timestamp = datetime.datetime.now(datetime.timezone.utc).isoformat()

    out_p = Path(output_header_path).resolve()
    out_p.parent.mkdir(parents=True, exist_ok=True)

    # Format bytes as hex literals (12 bytes per line)
    hex_lines: List[str] = []
    line_buffer: List[str] = []
    for i, byte_val in enumerate(model_bytes):
        line_buffer.append(f"0x{byte_val:02x}")
        if (i + 1) % 12 == 0:
            hex_lines.append("    " + ", ".join(line_buffer) + ",")
            line_buffer = []
    if line_buffer:
        hex_lines.append("    " + ", ".join(line_buffer))

    c_array_body = "\n".join(hex_lines)

    header_content = f"""/* ==============================================================================
 * Edge AI Compression Pipeline - Auto-Generated Model Data
 * Target: ESP32-S3 / TensorFlow Lite for Microcontrollers (TFLM)
 *
 * Source Model: {tflite_p.name}
 * Byte Length:  {byte_len} bytes
 * SHA-256 Hash: {sha256_hash}
 * Export Time:  {timestamp}
 *
 * WARNING: Do not edit this file manually. Any modification will invalidate
 * the cryptographic integrity check.
 * ============================================================================== */

#ifndef MODEL_DATA_H_
#define MODEL_DATA_H_

#ifdef __cplusplus
extern "C" {{
#endif

// Alignment requirement for TensorFlow Lite Micro tensor arena & weights
#if defined(__GNUC__) || defined(__clang__)
#define TFLM_ALIGN __attribute__((aligned(8)))
#elif defined(_MSC_VER)
#define TFLM_ALIGN __declspec(align(8))
#elif defined(__cplusplus) && __cplusplus >= 201103L
#define TFLM_ALIGN alignas(8)
#else
#define TFLM_ALIGN
#endif

// Cryptographic hash for build-time and runtime verification
#define MODEL_DATA_SHA256 "{sha256_hash}"

// Total byte length of the TFLite model FlatBuffer
extern const unsigned int {len_name};

// Model FlatBuffer binary payload
extern const unsigned char {array_name}[] TFLM_ALIGN;

#ifdef __cplusplus
}}
#endif

// Definition in header for header-only embedded integration
#if defined(MODEL_DATA_IMPLEMENTATION) || !defined(MODEL_DATA_HEADER_ONLY)
const unsigned int {len_name} = {byte_len};

const unsigned char {array_name}[] TFLM_ALIGN = {{
{c_array_body}
}};
#endif // MODEL_DATA_IMPLEMENTATION

#endif // MODEL_DATA_H_
"""

    with open(out_p, "w", encoding="utf-8") as f:
        f.write(header_content)

    # Generate model_labels.h if requested or by default in same directory
    labels_p = Path(labels_header_path).resolve() if labels_header_path else out_p.parent / "model_labels.h"
    _, ds_cfg = load_config()
    idx_to_class = ds_cfg.get_idx_to_class()
    num_classes = len(idx_to_class)

    labels_array_entries = []
    enum_entries = []
    for idx in range(num_classes):
        label = idx_to_class[idx]
        labels_array_entries.append(f'    "{label}"')
        sanitized_enum = label.strip("_").upper()
        if label.startswith("_"):
            sanitized_enum = "SPECIAL_" + sanitized_enum
        enum_entries.append(f"    LABEL_{sanitized_enum} = {idx}")

    enum_str = ",\n".join(enum_entries)
    labels_str = ",\n".join(labels_array_entries)

    labels_code = f"""/* ==============================================================================
 * Edge AI Compression Pipeline - Auto-Generated Class Label Mappings
 * Target: 12-Class Keyword Spotting (10 target words + silence + unknown)
 * Generated: {timestamp}
 * ============================================================================== */

#ifndef MODEL_LABELS_H_
#define MODEL_LABELS_H_

#ifdef __cplusplus
extern "C" {{
#endif

#define MODEL_NUM_CLASSES {num_classes}

typedef enum {{
{enum_str}
}} ModelClassId;

extern const char* const kModelLabels[MODEL_NUM_CLASSES];

#ifdef __cplusplus
}}
#endif

#if defined(MODEL_LABELS_IMPLEMENTATION) || !defined(MODEL_LABELS_HEADER_ONLY)
const char* const kModelLabels[MODEL_NUM_CLASSES] = {{
{labels_str}
}};
#endif // MODEL_LABELS_IMPLEMENTATION

#endif // MODEL_LABELS_H_
"""
    with open(labels_p, "w", encoding="utf-8") as f:
        f.write(labels_code)

    manifest_data = {
        "source_model_path": str(tflite_p),
        "source_model_filename": tflite_p.name,
        "byte_length": byte_len,
        "sha256": sha256_hash,
        "export_timestamp": timestamp,
        "array_name": array_name,
        "len_name": len_name,
        "header_path": str(out_p),
        "labels_path": str(labels_p),
        "num_classes": num_classes,
        "class_mapping": idx_to_class,
    }

    manifest_p = Path(manifest_path).resolve() if manifest_path else out_p.parent / "model_export_manifest.json"
    with open(manifest_p, "w", encoding="utf-8") as f:
        json.dump(manifest_data, f, indent=2)

    return manifest_data


def verify_c_header_integrity(
    header_path: Union[str, Path],
    original_tflite_path: Union[str, Path],
) -> Tuple[bool, Dict[str, Any]]:
    """Parse bytes out of the generated C header and verify exact byte-for-byte identity.

    Args:
        header_path: Path to the generated model_data.h header.
        original_tflite_path: Path to the original .tflite file.

    Returns:
        Tuple of (is_valid: bool, details: dict).
    """
    header_p = Path(header_path).resolve()
    tflite_p = Path(original_tflite_path).resolve()

    if not header_p.is_file():
        return False, {"error": f"Header file missing: {header_p}"}
    if not tflite_p.is_file():
        return False, {"error": f"Original model file missing: {tflite_p}"}

    with open(tflite_p, "rb") as f:
        original_bytes = f.read()

    header_text = header_p.read_text(encoding="utf-8")

    # Extract all hex numbers of the form 0x[0-9a-fA-F]{2} in the file body
    hex_matches = re.findall(r"0x([0-9a-fA-F]{2})", header_text)
    if not hex_matches:
        return False, {"error": "No hex byte literals found in header file"}

    reconstructed_bytes = bytes(int(h, 16) for h in hex_matches)

    orig_len = len(original_bytes)
    recon_len = len(reconstructed_bytes)
    orig_sha = hashlib.sha256(original_bytes).hexdigest()
    recon_sha = hashlib.sha256(reconstructed_bytes).hexdigest()

    len_match = (orig_len == recon_len)
    sha_match = (orig_sha == recon_sha)
    byte_match = (original_bytes == reconstructed_bytes)

    is_valid = len_match and sha_match and byte_match

    return is_valid, {
        "length_match": len_match,
        "sha256_match": sha_match,
        "exact_byte_match": byte_match,
        "original_length": orig_len,
        "reconstructed_length": recon_len,
        "original_sha256": orig_sha,
        "reconstructed_sha256": recon_sha,
    }


