    project_root = Path(__file__).resolve().parent.parent.parent
    tflite_file = project_root / "models" / "quantized" / "baseline_dscnn_int8.tflite"
    out_header = project_root / "deployment" / "esp32" / "include" / "model_data.h"
    out_labels = project_root / "deployment" / "esp32" / "include" / "model_labels.h"

    print(f"Exporting {tflite_file} -> {out_header}...")
    manifest = export_tflite_to_c_header(tflite_file, out_header, out_labels)
    print(f"Exported {manifest['byte_length']} bytes, SHA-256: {manifest['sha256']}")

    valid, details = verify_c_header_integrity(out_header, tflite_file)
    print(f"Cryptographic verification passed: {valid}")
    if not valid:
        print("Details:", details)
